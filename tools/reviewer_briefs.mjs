// Writes docs/reviewer-briefs.md: one brief per path for inviting expert reviewers.
// Each brief: size, time needed, who should review it (from the path's own checklist),
// and the works to look at first (intros that mention a dispute, a critic or a contested claim).
// Run: node tools/reviewer_briefs.mjs
import fs from "node:fs";
import { parsePath } from "../src/content.js";
import { PATHS } from "../src/paths.js";

const dir = new URL("../paths/", import.meta.url);
const HOT = /disput|debat|critic|challeng|contest|question(ed)?\b|controvers|disagree|one side/i;
const out = [`# Reviewer briefs

One brief per path, to attach to the reviewer invitation in docs/pilot-kit.md. Generated by \`node tools/reviewer_briefs.mjs\` from the path files, so rerun it after editing a path.

Every path is a draft written with AI help from published sources, then checked by an editor. Reviewers are asked to:

1. **Check facts.** Dates, names, prizes, editions and what each work says.
2. **Check balance.** Are the works and voices fair to the field and to its traditions around the world?
3. **Check the quizzes.** Each question should have exactly one defensible answer.
4. **Check access labels.** Free works must be legally free.
5. **Endorse, suggest or flag** each work in the Review tab, then endorse or decline the whole path.

Time: about 10 minutes per work to skim the introduction and quiz, so 4 to 5 hours for a full path. Reviewers may split a path by stage.
`];

for (const m of PATHS) {
  const text = fs.readFileSync(new URL(`${m.slug}.md`, dir), "utf8"), p = parsePath(text);
  const qs = p.works.reduce((n, w) => n + w.quiz.length, 0);
  const who = (text.match(/^- \[ \] Reviewed by (.+)$/m) || [])[1] || "experts in the field";
  const extra = [...text.matchAll(/^- \[ \] (?!Reviewed by|Every `\[verify\]`|Every access label|Every quiz question)(.+)$/gm)].map(x => x[1]);
  const hot = p.works.filter(w => HOT.test((w.layers || []).filter(l => l.name !== "Quiz").map(l => l.body).join(" "))).map(w => `${w.title} (${w.id})`);
  out.push(`## ${m.title}

- **Size:** ${p.stages.length} stages, ${p.works.length} works, ${qs} quiz questions.
- **Ideal reviewers:** ${who}.
- **Link:** https://wasiulbahar.com/ascent/#/path/${m.slug}
${extra.map(e => `- **Also check:** ${e}`).join("\n")}${extra.length ? "\n" : ""}- **Look first at:** ${hot.length ? hot.join("; ") : "no works are marked as contested; check the timeline and trivia first"}.
`);
}
fs.writeFileSync(new URL("../docs/reviewer-briefs.md", import.meta.url), out.join("\n"));
console.log(`reviewer briefs written for ${PATHS.length} paths`);
